function index01(arr, n) {
  if (arr.length <= n) return -1;
  return Math.pow(arr[n], n);
}
console.log(index01([1, 2, 3, 4], 2));

//  ╭─────────────────────────────────────────────────────────────────────────╮
//  │ METHOD 02                                                               │
//  ╰─────────────────────────────────────────────────────────────────────────╯
function index02(arr, n) {
  return arr.length <= n ? -1 : Math.pow(arr.at(n), n);
}
console.log(index02([1, 2, 3, 4], 2));
