function stringy01(size) {
  let result = "";
  for (let i = 0; i < size; i += 2) {
    result += "10";
  }
  return result;
}
console.log(stringy01(22));

//  ╭─────────────────────────────────────────────────────────────────────────╮
//  │ METHOD 02                                                               │
//  ╰─────────────────────────────────────────────────────────────────────────╯
function stringy02(size) {
  let result = "";
  for (let i = 1; i <= size; i++) {
    result += i % 2 === 0 ? "0" : "1";
  }
  return result;
}
console.log(stringy02(22));

//  ╭─────────────────────────────────────────────────────────────────────────╮
//  │ METHOD 03                                                               │
//  ╰─────────────────────────────────────────────────────────────────────────╯
function stringy03(size) {
  let result = Array(size)
    .fill(0)
    .map((_, i) => ((i + 1) % 2 === 0 ? 0 : 1))
    .join("");
  return result;
}
console.log(stringy03(22));

//  ╭─────────────────────────────────────────────────────────────────────────╮
//  │ METHOD 04                                                               │
//  ╰─────────────────────────────────────────────────────────────────────────╯
function stringy04(size) {
  let result = Array.from({ length: size }, (_, i) =>
    i % 2 !== 0 ? "0" : "1",
  ).join("");
  return result;
}
console.log(stringy04(22));
